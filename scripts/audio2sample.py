#!/usr/bin/env python3
"""
Audio-to-Sample C Header Converter for ATtiny85 / 8Bit Mixtape.

Converts any audio file (WAV, MP3, OGG, FLAC, AAC) into an 8-bit unsigned PCM
PROGMEM C header file optimized for Flash memory constraints on the ATtiny85.

Features:
  - Trims leading and trailing silence
  - Normalizes dynamic range
  - Resamples cleanly to fit the exact Flash byte budget (default: 3800 bytes)
  - Centers audio at unsigned 128 (8-bit PWM DAC midpoint)
  - Outputs formatted PROGMEM C header ready for #include

Usage:
  python3 scripts/audio2sample.py input.wav -o include/my_sample.h
  python3 scripts/audio2sample.py voice.mp3 --length 3800 --var sample_data
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path


def convert_audio(input_path: Path, target_len: int = 3800, trim_silence: bool = True) -> list:
    """Decode, normalize, resample, and convert audio to unsigned 8-bit PCM values."""
    # Step 1: Use ffmpeg to decode input to a normalized float mono stream
    # ffmpeg decodes any audio container, mixes to mono, and outputs 32-bit float PCM
    cmd = [
        "ffmpeg", "-y",
        "-i", str(input_path),
        "-vn",
        "-ac", "1",
        "-f", "f32le",
        "pipe:1"
    ]
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=True)
    raw_bytes = proc.stdout

    import struct
    num_samples = len(raw_bytes) // 4
    if num_samples == 0:
        raise ValueError(f"No audio samples decoded from {input_path}")

    floats = list(struct.unpack(f"<{num_samples}f", raw_bytes))

    # Step 2: Trim silence (threshold ~ 0.03)
    if trim_silence:
        thresh = 0.03
        start_idx = 0
        while start_idx < len(floats) and abs(floats[start_idx]) < thresh:
            start_idx += 1
        end_idx = len(floats) - 1
        while end_idx > start_idx and abs(floats[end_idx]) < thresh:
            end_idx -= 1
        
        if end_idx > start_idx:
            floats = floats[start_idx : end_idx + 1]

    # Step 3: Resample to exact target_len using linear interpolation
    orig_len = len(floats)
    if orig_len == 0:
        raise ValueError("Audio is completely silent after trimming")

    resampled = []
    ratio = (orig_len - 1) / max(1, target_len - 1)
    for i in range(target_len):
        pos = i * ratio
        idx = int(pos)
        frac = pos - idx
        if idx + 1 < orig_len:
            val = floats[idx] * (1.0 - frac) + floats[idx + 1] * frac
        else:
            val = floats[idx]
        resampled.append(val)

    # Step 4: Normalize peak to 0.95
    peak = max(abs(v) for v in resampled)
    scale = (0.95 / peak) if peak > 0.001 else 1.0

    # Step 5: Convert to 8-bit unsigned PCM (0..255, center=128)
    uint8_samples = []
    for v in resampled:
        norm = v * scale
        # Clamp to -1.0 .. +1.0
        norm = max(-1.0, min(1.0, norm))
        # Center at 128
        byte_val = int(round(128.0 + norm * 127.0))
        byte_val = max(0, min(255, byte_val))
        uint8_samples.append(byte_val)

    return uint8_samples


def write_header(samples: list, output_path: Path, var_name: str = "sample_data", len_name: str = "sample_len"):
    """Write C PROGMEM header file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    lines.append("// Generated by scripts/audio2sample.py")
    lines.append("// Unsigned 8-bit PCM audio sample for ATtiny85 PWM playback")
    lines.append("#pragma once")
    lines.append("#include <avr/pgmspace.h>")
    lines.append("")
    lines.append(f"const unsigned int {len_name} = {len(samples)};")
    lines.append(f"const unsigned char {var_name}[] PROGMEM = {{")

    # Format 16 values per row
    row = []
    for i, s in enumerate(samples):
        row.append(f"{s:3d}")
        if len(row) == 16 or i == len(samples) - 1:
            comma = "," if i < len(samples) - 1 else ""
            lines.append("  " + ", ".join(row) + comma)
            row = []

    lines.append("};")
    lines.append("")

    output_path.write_text("\n".join(lines))
    print(f"==> Successfully generated {output_path} ({len(samples)} samples, {output_path.stat().st_size} bytes)")


def main():
    parser = argparse.ArgumentParser(description="Convert audio to ATtiny85 C header sample")
    parser.add_argument("input", type=Path, help="Input audio file (WAV, MP3, OGG, FLAC)")
    parser.add_argument("-o", "--output", type=Path, default=Path("include/sample.h"), help="Output header path (default: include/sample.h)")
    parser.add_argument("-l", "--length", type=int, default=3800, help="Target sample length in bytes (default: 3800)")
    parser.add_argument("--var", type=str, default="sample_data", help="Variable name (default: sample_data)")
    parser.add_argument("--len-var", type=str, default="sample_len", help="Length constant name (default: sample_len)")
    parser.add_argument("--no-trim", action="store_true", help="Do not trim silence")

    args = parser.parse_args()

    if not args.input.exists():
        print(f"Error: Input file '{args.input}' not found", file=sys.stderr)
        sys.exit(1)

    print(f"Converting '{args.input}' -> '{args.output}' (target length: {args.length} bytes)...")
    samples = convert_audio(args.input, target_len=args.length, trim_silence=not args.no_trim)
    write_header(samples, args.output, var_name=args.var, len_name=args.len_var)


if __name__ == "__main__":
    main()
